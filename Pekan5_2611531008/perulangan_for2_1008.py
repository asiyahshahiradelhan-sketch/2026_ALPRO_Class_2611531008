# Buat program untuk perulangan for dalam Python
# Nama variabel ditambah 4 digit nim terakhir contoh: ulang_1008
# Program ini menggunakan fungsi input()

ulang_1008 = int(input("MAsukkan jumlah perulangan: "))
print("Perulangan ke-0 sampai ke-", ulang_1008-1)
for i_1008 in range(ulang_1008):
    print(i_1008, end=" ")
print()
print("Perulangan ke-1 sampai ke-", ulang_1008)
for i_1008 in range(1, ulang_1008+1):
    print(i_1008, end=" ")
