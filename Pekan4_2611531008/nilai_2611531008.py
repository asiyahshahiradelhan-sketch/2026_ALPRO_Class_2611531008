# Nama variabel ditambah 4 digit nim terakhir contoh: ipk_1008
# Program ini menggunakan fungsi input()
# program konversi nilai angka menjadi huruf

nilai_1008 = int("Input(Input nilai angka: ")

if nilai_1008 >= 81:
    print("A")
elif nilai_1008 >= 70:
    print("B")
elif nilai_1008 >= 60:
    print("C")
elif nilai_1008 >= 50:
    print("D")
else:
    print("E")